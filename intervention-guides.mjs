export function reframesFor(entry, chapterId) {
 const chapter = guidebook[chapterId];
 return [
  `“${entry.problem}” describes a difficulty to understand and work with. It does not need to become a verdict about your character.`,
  `The first aim can be to test “${entry.title.toLowerCase()}” in one suitable situation, then use what happens as information.`,
  ...chapter.reframes
 ];
}

